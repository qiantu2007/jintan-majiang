/* 金坛麻将 · 联机消息约定
 *
 * 客户端（src/net.js）和服务端（_服务端/worker.js）之间就靠这些消息说话。
 * 这个文件是那份约定的**唯一书面版本**，`_测试_协议.mjs` 会拿它去核对两边的
 * 代码：服务端发的每一种客户端都得接得住，客户端发的每一种服务端都得认，
 * 而且都必须在这里登记过。少一边、拼错一个字母，测试就红。
 *
 * 为什么专门做这件事：这是整个项目里最容易「改一处漏一处」的地方。
 * 规则算错了当场就看得出来，但消息类型对不上是**无声**的 ——
 * 服务端照发，客户端不认识就丢掉，牌局停在那儿，控制台一片干净。
 * 而且只有真的四个人连上打的时候才会暴露。
 *
 * 加一种新消息的步骤：先在这里登记，再改两边的代码，然后跑测试。
 */

